  `${LABELS[lang].nakshatra[p[0]]} ${p[1]} \u00B7 ${LABELS[lang].planets[STAR_LORD_CYCLE[p[0] % 9]]}` +
  (isVargottamaPada(p) ? ` (${VARGOTTAMA_WORD[lang]})` : "");

